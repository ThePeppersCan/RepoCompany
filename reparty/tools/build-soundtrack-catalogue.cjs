// Catalogue corrections belong in supabase/soundtrack-catalogue.json. No network required.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const rows=JSON.parse(fs.readFileSync(root+'/supabase/soundtrack-catalogue.json','utf8'));
const ids=new Set(),counts=[];
for(const r of rows){
 assert(!ids.has(r.id),'Duplicate catalogue ID');ids.add(r.id);
 assert(['game','movie','disney','popular'].includes(r.category)&&r.title&&r.track&&r.aliases?.length,'Incomplete track');
 assert(Number.isInteger(r.difficulty)&&r.difficulty>=1&&r.difficulty<=5,'Invalid difficulty');
 assert(!r.video_id||/^[A-Za-z0-9_-]{11}$/.test(r.video_id),'Invalid video ID');
 assert(Number.isFinite(r.start_seconds)&&r.start_seconds>=0,'Invalid start time');
 let c=counts.find(x=>x.category===r.category&&x.difficulty===r.difficulty);
 if(!c){c={category:r.category,difficulty:r.difficulty,total:0,playable:0};counts.push(c);}c.total++;if(r.video_id)c.playable++;
}
const fields=['id','category','title','track','composer','year','difficulty','aliases','video_id','start_seconds'];
const payload=JSON.stringify(rows.map(r=>Object.fromEntries(fields.map(k=>[k,r[k]]))));
assert(!payload.includes('$catalogue$'));
const sql=`-- Generated by tools/build-soundtrack-catalogue.cjs. Apply after soundtrack migration.\n-- Includes the original workbook, Disney expansion and chart-based popular songs. Linked sources still need listening review.\nbegin;\ninsert into reparty_private.soundtracks (${fields.join(',')})\nselect ${fields.join(',')} from jsonb_to_recordset($catalogue$${payload}$catalogue$::jsonb)\nas x(id text,category text,title text,track text,composer text,year integer,difficulty integer,aliases jsonb,video_id text,start_seconds double precision)\non conflict(id) do update set ${fields.slice(1).map(k=>k+'=excluded.'+k).join(',')};\ncommit;\n`;
fs.writeFileSync(root+'/supabase/soundtrack-catalogue.sql',sql);
// Category-only releases do not overwrite corrections to unrelated live entries.
for(const category of ['disney','popular']){
 const subset=rows.filter(r=>r.category===category).map(r=>Object.fromEntries(fields.map(k=>[k,r[k]])));
 if(!subset.length)continue;
 const categorySql=sql.replace(/^--[^\n]*\n--[^\n]*\n/,`-- Generated ${category}-only seed. Apply after its category migration.\n`).replace(payload,()=>JSON.stringify(subset));
 fs.writeFileSync(root+`/supabase/${category}-soundtrack-catalogue.sql`,categorySql);
}
fs.mkdirSync(root+'/soundtracks',{recursive:true});
// The server draws distinct recordings, including overlaps between movie and Disney.
const mixes=Object.fromEntries(['game','movie','disney','popular','mixed'].map(category=>[category,
 Object.fromEntries([1,2,3,4,5].map(difficulty=>[difficulty,new Set(rows.filter(r=>r.video_id&&(category==='mixed'||r.category===category)&&r.difficulty<=difficulty).map(r=>r.video_id)).size]))]));
fs.writeFileSync(root+'/soundtracks/summary.json',JSON.stringify({total:rows.length,linked:rows.filter(r=>r.video_id).length,counts,mixes},null,2)+'\n');
console.log(`${rows.length} entries, ${rows.filter(r=>r.video_id).length} linked tracks. Seed and summary generated.`);
